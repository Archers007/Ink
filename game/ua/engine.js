// Union Arena rules engine: a pure, synchronous, server-authoritative state machine (same shape as game/engine.js).
//
//   newGame({ players: [{ name, cards: [[no, qty]] }], defs, seed })  -> state (plain JSON)
//   applyAction(state, seat, action)                                   -> events; throws RuleError and leaves the
//                                                                         state untouched when the action is illegal
//   legalActions(state, seat)                                          -> the actions that seat may take now
//   viewFor(state, seat)                                               -> what that seat may see (hands, decks, life
//                                                                         and face-down cards hidden)
//
// Rules are cited as UA-x (docs/rules/ua/rule_manual.md). What is automated:
//   setup + one mulligan each, Player One decides first [UA-5] · start phase: expiries, untap, AP table, draw, extra
//   draw for 1 AP [UA-8.1] · movement, Step, full-line removal [UA-8.2] · required energy by colour from the energy
//   line, AP costs, playing characters/sites/events, Raid [UA-8.3] · Activate: Main abilities, Once Per Turn ·
//   attacks, Snipe, blocks, battles, Impact, Damage, Double Attack/Block, Nullify Impact [UA-8.4, UA-10] · damage and
//   life triggers (Draw, Get, Raid, Active, and card-specific ones) [UA-8.4] · end phase: untap characters/sites, hand
//   limit 8 [UA-8.5] · BP 0 or less sidelines [UA-9] · raided stacks leaving the field [UA-9] · win by life or deck-out.
//
// Card abilities come from game/ua/compile.js (effect text -> ops) and run in game/ua/effects.js. A line the compiler
// can't read is resolved by hand: its owner gets primitive table actions (draw, move a card, rest/activate, BP) and
// says when they're done, as at a real table.

import { compileDef } from './compile.js';
import { runOps, evalCond, staticMods, matches } from './effects.js';

export class RuleError extends Error {}
const RE = (m) => new RuleError(m);

export const HAND_LIMIT = 8, OPENING = 7, LIFE = 7, LINE_MAX = 4;
export const AP_TABLE = [[1, 2, 3], [2, 2, 3]];       // [seat][turn-1], 3 from turn 3 on (UA-8.1)

// ---------- rng ----------
export function rand(s) {
  s.rng = (s.rng + 0x6D2B79F5) | 0;
  let t = s.rng;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
export function shuffle(s, a) {
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rand(s) * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}

// ---------- helpers ----------
export const P = (s, seat) => s.players[seat];
export const C = (s, iid) => s.cards[iid];
export const D = (s, c) => s.defs[(typeof c === 'string' ? s.cards[c] : c).no];
export const other = (seat) => 1 - seat;
export const nameOf = (s, seat) => s.players[seat]?.name || `Player ${seat + 1}`;
const FIELD = new Set(['front', 'energy']);
export const onField = (c) => !!c && FIELD.has(c.zone);
export const cardName = (s, c) => D(s, c)?.name || '?';

export function log(s, text, ev, extra = {}) {
  const e = { t: 'log', text, seq: ++s.seq, ...extra };
  s.log.push(e);
  if (s.log.length > 400) s.log.splice(0, s.log.length - 400);
  ev?.push(e);
  return e;
}

// ---------- derived values: BP, keywords, energy ----------
// mods on the card + static abilities currently applying to it
export function modsOf(s, c) {
  return [...(c.mods || []), ...staticMods(s, c)];
}
export function bpOf(s, c) {
  const d = D(s, c);
  if (d.bp == null) return null;
  return modsOf(s, c).reduce((n, m) => n + (m.bp || 0), d.bp);
}
export function kwOf(s, c) {
  const kw = { ...(D(s, c).kw || {}) };
  for (const m of modsOf(s, c)) {
    if (!m.kw) continue;
    for (const [k, v] of Object.entries(m.kw)) {
      if (k === 'impactPlus' || k === 'damagePlus') kw[k] = (kw[k] || 0) + v;
      else if (k === 'damage') kw.damage = Math.max(kw.damage || 1, v);
      else if (k === 'impact') kw.impact = 1;
      else kw[k] = v;
    }
    if (m.loseKw) for (const k of m.loseKw) delete kw[k];
  }
  if (kw.impactPlus && !kw.impact) kw.impact = 1;     // Impact +1 grants Impact 1 (UA-10)
  return kw;
}
export const hasKw = (s, c, k) => !!kwOf(s, c)[k];
export function flagOf(s, c, flag) { return modsOf(s, c).some((m) => m[flag]); }

// energy generated by a player's energy line, by colour (UA-3: front line generation doesn't count)
export function energyOf(s, seat) {
  const out = {};
  for (const iid of [...P(s, seat).energy, ...P(s, seat).front]) {
    const c = C(s, iid);
    const mods = modsOf(s, c);
    if (c.zone === 'front' && !mods.some((m) => m.genFront)) continue;   // "generates energy even if it is on the front line"
    const gens = [...(D(s, c).gen || [])];
    for (const m of mods) if (m.gen) gens.push(...m.gen);
    for (const g of gens) out[g] = (out[g] || 0) + 1;
  }
  out.any = Object.values(out).reduce((a, b) => a + b, 0);
  return out;
}
// "reduce this card's required energy / AP cost by N while in your hand"
function handMod(s, seat, c, key) {
  if (!c?.iid) return 0;
  let n = 0;
  for (const m of s.compiled[c.no]?.handMods || []) {
    if (!m[key] || (m.cond && !evalCond(s, m.cond, { src: c.iid, seat }))) continue;
    n += m.per ? m[key] * Math.floor(P(s, seat)[m.per.zone].length / m.per.n) : m[key];
  }
  return n;
}
export function energyNeed(s, seat, c) {
  const d = D(s, c);
  return Math.max(0, (d.energy || 0) + handMod(s, seat, c, 'energy'));
}
export function energyOk(s, seat, d, c = null) {
  const need = c ? energyNeed(s, seat, c) : d.energy || 0;
  if (!need) return true;
  return (energyOf(s, seat)[d.color] || 0) >= need;
}
export const apActive = (s, seat) => P(s, seat).ap.filter((a) => a).length;
export function apCost(s, seat, c) {
  const d = D(s, c);
  let n = (d.ap ?? 0) + handMod(s, seat, c, 'ap');
  for (const m of [...(P(s, seat).costMods || [])]) if (m.filter ? matches(s, c, m.filter, seat) : true) n += m.ap || 0;
  return Math.max(0, n);
}
export function payAp(s, seat, n) {
  const ap = P(s, seat).ap;
  if (apActive(s, seat) < n) throw RE(`That needs ${n} AP and you have ${apActive(s, seat)} active.`);
  for (let i = 0, left = n; i < ap.length && left > 0; i++) if (ap[i]) { ap[i] = false; left--; }
}

// ---------- moving cards ----------
function listFor(s, c) {
  const p = P(s, c.owner);
  switch (c.zone) {
    case 'deck': return p.deck; case 'hand': return p.hand; case 'life': return p.life; case 'side': return p.side;
    case 'removal': return p.removal; case 'front': return p.front; case 'energy': return p.energy; case 'check': return p.check;
    default: return null;
  }
}
function detach(s, c) {
  if (c.zone === 'under') {
    const parent = C(s, c.parent);
    if (parent) parent.under = parent.under.filter((x) => x !== c.iid);
    c.parent = null;
    return;
  }
  const list = listFor(s, c);
  if (list) { const i = list.indexOf(c.iid); if (i >= 0) list.splice(i, 1); }
}
const freshOnField = (s, c) => { c.rest = true; c.mods = []; c.once = {}; c.attacks = 0; c.blocks = 0; c.enteredTurn = s.turnNo; c.uid = ++s.seq; };

// Move a card. to: 'hand'|'deckTop'|'deckBottom'|'life'|'side'|'removal'|'front'|'energy'.
// sideline: true when this is "sidelining" (UA-9) so When Sidelined fires. A raided stack leaving the field: only the top
// card goes to `to`; the cards under it go to the sideline without being sidelined (UA-9).
export function moveCard(s, iid, to, ev, opt = {}) {
  const c = C(s, iid);
  const wasField = onField(c);
  const from = c.zone;
  detach(s, c);
  if (wasField && c.under.length) {
    for (const u of c.under) { const uc = C(s, u); uc.zone = 'side'; uc.parent = null; P(s, uc.owner).side.push(u); }
    c.under = [];
  }
  const p = P(s, c.owner);
  if (to === 'deckTop') { c.zone = 'deck'; p.deck.unshift(iid); }
  else if (to === 'deckBottom') { c.zone = 'deck'; p.deck.push(iid); }
  else if (to === 'lifeTop' || to === 'life') { c.zone = 'life'; p.life.unshift(iid); }
  else if (to === 'front' || to === 'energy') {
    c.zone = to; p[to].push(iid);
    if (!FIELD.has(from)) freshOnField(s, c);
    if (opt.active) c.rest = false;
  } else { c.zone = to; p[to].push(iid); }
  if (!FIELD.has(to)) { c.rest = false; c.mods = []; }
  if (wasField && !FIELD.has(to) && opt.sideline && to === 'side') {
    fire(s, 'sidelined', { iid, seat: c.owner, from }, ev);
  }
  return c;
}

// "sideline" a card on the field (battle loss, BP ≤ 0, an ability that says sideline)
export function sideline(s, iid, ev, why = '') {
  const c = C(s, iid);
  if (!onField(c)) return false;
  if (D(s, c).type === 'character') {
    (s.sidelinedTurn ||= {})[c.owner] = s.turnNo;
    if (s.sidelinedCount?.turn !== s.turnNo) s.sidelinedCount = { turn: s.turnNo, n: 0 };
    s.sidelinedCount.n++;
  }
  log(s, `${cardName(s, c)} is sidelined${why ? ` (${why})` : ''}.`, ev);
  moveCard(s, iid, 'side', ev, { sideline: true });
  return true;
}

// a line is full: the player picks one card on it to go to the removal area first (UA-8.2, UA-8.3)
function makeRoom(s, seat, line, removeIid, ev) {
  const p = P(s, seat);
  if (p[line].length < LINE_MAX) return;
  if (!removeIid || !p[line].includes(removeIid)) throw RE(`Your ${line === 'front' ? 'front line' : 'energy line'} is full: choose a card on it to put into your removal area.`);
  log(s, `${nameOf(s, seat)} puts ${cardName(s, C(s, removeIid))} into the removal area to make room.`, ev);
  moveCard(s, removeIid, 'removal', ev);
}

export function drawCards(s, seat, n, ev) {
  const p = P(s, seat);
  let drawn = 0;
  for (let i = 0; i < n; i++) {
    if (!p.deck.length) { log(s, `${nameOf(s, seat)} has no cards left to draw.`, ev); break; }
    const iid = p.deck.shift();
    C(s, iid).zone = 'hand';
    p.hand.push(iid);
    drawn++;
  }
  if (drawn) log(s, `${nameOf(s, seat)} draws ${drawn === 1 ? 'a card' : `${drawn} cards`}.`, ev, { draw: seat, n: drawn });
  return drawn;
}

export function win(s, seat, reason, ev) {
  if (s.winner != null) return;
  s.winner = seat;
  s.phase = 'over';
  s.pending = null;
  s.queue = [];
  s.cont = [];
  log(s, `${nameOf(s, seat)} wins: ${reason}.`, ev, { over: true });
}

// ---------- triggers ----------
// Collect abilities with this timing on cards that are on the field (or the card itself for its own events), then
// queue them: the turn player's first, then the other player's (UA-9).
export function fire(s, event, info, ev) {
  if (s.winner != null) return;
  const jobs = [];
  const seen = new Set();
  const consider = (c) => {
    if (!c || seen.has(c.iid)) return;
    seen.add(c.iid);
    // the card's own abilities, then abilities it was given for a while ("gains "When this character attacks …"")
    const ab = [...(s.compiled[c.no]?.abilities || []), ...(onField(c) ? (c.mods || []).filter((m) => m.grant).map((m) => m.grant) : [])];
    ab.forEach((a, idx) => {
      if (a.timing !== event && !(a.also || []).includes(event)) return;
      if (!triggerApplies(s, c, a, event, info)) return;
      if (a.once && c.once?.[idx] === s.turnNo) return;
      if (a.once) (c.once ||= {})[idx] = s.turnNo;
      jobs.push(newJob(s, c, a, idx, info));
    });
  };
  // the card's own event, even when it has just left the field (When Sidelined)
  if (info?.iid) consider(C(s, info.iid));
  for (const seat of [s.active, other(s.active)]) {
    for (const iid of [...P(s, seat).front, ...P(s, seat).energy]) consider(C(s, iid));
  }
  jobs.sort((a, b) => (a.seat === s.active ? 0 : 1) - (b.seat === s.active ? 0 : 1));
  s.queue.push(...jobs);
}
function triggerApplies(s, c, a, event, info) {
  // abilities of a card only see their own card's events unless the ability says otherwise (a.watch)
  if (event === 'endPhase' || event === 'startTurn' || event === 'attackPhase') {                // "at the start of your end phase / turn"
    if (!onField(c) || c.owner !== info.seat) return false;
    return !a.cond || evalCond(s, a.cond, { src: c.iid, seat: c.owner, info });
  }
  const self = info?.iid === c.iid;
  if (!a.watch && !self) return false;
  if (a.watch && !matches(s, C(s, info.iid), a.watch, c.owner)) return false;
  if (!a.watch && !onField(c) && event !== 'sidelined') return false;
  if (a.cond && !evalCond(s, a.cond, { src: c.iid, seat: c.owner, info })) return false;
  return true;
}
export function newJob(s, c, a, idx, info = {}) {
  return { id: ++s.seq, src: c.iid, no: c.no, seat: c.owner, ab: idx, kind: a.kind || 'ability', ops: a.ops, manual: a.manual || null, text: a.text, i: 0, ctx: { info, vars: {} } };
}

// ---------- the pump: resolve queued abilities, then continue the rules procedure ----------
// s.cont is a stack of rules steps waiting for the queue to drain (battle steps, life checks, end phase …).
export function pump(s, ev) {
  for (let guard = 0; guard < 2000; guard++) {
    if (s.winner != null || s.pending) return;
    stateCheck(s, ev);
    if (s.winner != null || s.pending) return;
    if (s.queue.length) {
      const job = s.queue[0];
      if (job.manual && !job.ops?.length) {
        s.pending = { type: 'manual', seat: job.seat, job: job.id, text: job.text, card: job.src, prompt: `Resolve by hand: ${job.text}` };
        return;
      }
      const r = runOps(s, job, ev);
      if (r === 'wait') return;
      s.queue.shift();
      continue;
    }
    if (s.cont.length) { const step = s.cont.pop(); STEPS[step.k](s, step, ev); continue; }
    return;
  }
  throw new Error('UA engine: resolution did not settle');
}

// BP 0 or less sidelines (UA-9); a player with no life left (and no life check under way) has lost (UA-6)
function stateCheck(s, ev) {
  if (s.phase !== 'mulligan') {
    for (const seat of [0, 1]) {
      const p = P(s, seat);
      if (!p.life.length && !p.check.length && !s.cont.some((x) => x.k === 'lifeCheck' && x.seat === seat)) {
        win(s, other(seat), `${nameOf(s, seat)} has no life left`, ev);
        return;
      }
    }
  }
  for (const seat of [0, 1]) {
    for (const iid of [...P(s, seat).front, ...P(s, seat).energy]) {
      const c = C(s, iid);
      if (D(s, c).type === 'character' && bpOf(s, c) <= 0) sideline(s, iid, ev, 'BP 0 or less');
    }
  }
}

// ---------- setup ----------
export function newGame({ players, defs, seed = Date.now() & 0x7fffffff, first = null }) {
  const s = {
    v: 1, rng: seed | 0, seed, seq: 0, defs: {}, compiled: {}, cards: {}, log: [],
    players: players.map((p) => ({
      name: p.name || 'Player', deck: [], hand: [], life: [], side: [], removal: [], front: [], energy: [], check: [],
      ap: [], turns: 0, extraDrawn: false, mulligan: null, costMods: [],
    })),
    active: 0, first: 0, turnNo: 0, phase: 'mulligan', pending: null, queue: [], cont: [], battle: null, winner: null,
  };
  let n = 0;
  players.forEach((p, seat) => {
    for (const [no, qty] of p.cards) {
      const d = defs.get ? defs.get(no) : defs[no];
      if (!d) throw RE(`Unknown card ${no}.`);
      s.defs[no] = d;
      s.compiled[no] ||= compileDef(d);
      for (let i = 0; i < qty; i++) {
        const iid = `c${++n}`;
        s.cards[iid] = { iid, no, owner: seat, zone: 'deck', rest: false, under: [], parent: null, mods: [], once: {}, attacks: 0, blocks: 0 };
        s.players[seat].deck.push(iid);
      }
    }
    shuffle(s, s.players[seat].deck);
  });
  s.first = first ?? (rand(s) < 0.5 ? 0 : 1);
  s.active = s.first;
  const ev = [];
  log(s, `${nameOf(s, s.first)} is Player One and goes first.`, ev);
  for (const seat of [0, 1]) drawCards(s, seat, OPENING, null);
  s.pending = { type: 'mulligan', seat: s.first, prompt: 'Keep this hand, or shuffle it away and draw 7 new cards (once)?' };
  return s;
}

function finishSetup(s, ev) {
  for (const seat of [0, 1]) {
    const p = P(s, seat);
    for (let i = 0; i < LIFE && p.deck.length; i++) { const iid = p.deck.shift(); C(s, iid).zone = 'life'; p.life.push(iid); }
  }
  log(s, 'Both players set 7 life cards.', ev);
  startTurn(s, s.first, ev);
}

// ---------- turn structure ----------
function startTurn(s, seat, ev) {
  s.active = seat;
  s.turnNo++;
  const p = P(s, seat);
  p.turns++;
  p.extraDrawn = false;
  s.phase = 'start';
  log(s, `— ${nameOf(s, seat)}'s turn ${p.turns} —`, ev, { turn: s.turnNo, seat });
  // 1. "until the start of your next turn" effects end
  expire(s, (m) => m.until === 'sont' && m.who === seat);
  // 2. untap everything
  for (const iid of [...p.front, ...p.energy]) C(s, iid).rest = false;
  p.ap = p.ap.map(() => true);
  // 3. AP cards for this turn
  const want = AP_TABLE[seat === s.first ? 0 : 1][Math.min(p.turns, 3) - 1];
  while (p.ap.length < want) p.ap.push(true);
  // 4. draw (Player One skips their first draw); no card to draw = lose (UA-6)
  const skip = seat === s.first && p.turns === 1;
  if (!skip) {
    if (!p.deck.length) { win(s, other(seat), `${nameOf(s, seat)} could not draw in their start phase`, ev); return; }
    drawCards(s, seat, 1, ev);
  }
  fire(s, 'startTurn', { seat }, ev);
  s.cont.push({ k: 'startChoice' });
}

// delayed abilities ("At the end of the main phase, sideline this character."): only while the card that made them is
// still the same card on the field
function runDelayed(s, at, ev) {
  const due = (s.delayed || []).filter((d) => d.at === at && d.turn === s.turnNo);
  s.delayed = (s.delayed || []).filter((d) => !due.includes(d) && d.turn >= s.turnNo);
  for (const d of due) {
    const c = C(s, d.src);
    if (!onField(c) || c.uid !== d.uid) continue;
    s.queue.push({ id: ++s.seq, src: d.src, no: c.no, seat: d.seat, ab: 'delayed', kind: 'delayed', ops: d.ops, text: d.text, i: 0, ctx: { info: {}, vars: {} } });
  }
}

function expire(s, pred) {
  for (const c of Object.values(s.cards)) if (c.mods?.length) c.mods = c.mods.filter((m) => !pred(m));
  for (const p of s.players) p.costMods = (p.costMods || []).filter((m) => !pred(m));
}

const STEPS = {
  startChoice(s) {
    s.pending = { type: 'phase', seat: s.active, phase: 'start', prompt: 'Start phase: pay 1 AP for an extra draw, or go on to movement.' };
  },
  toMove(s, step, ev) {
    s.phase = 'move';
    log(s, 'Movement phase.', ev, { phase: 'move' });
    s.pending = { type: 'phase', seat: s.active, phase: 'move', prompt: 'Move characters from your energy line to your front line, then go on.' };
  },
  toMain(s, step, ev) {
    s.phase = 'main';
    log(s, 'Main phase.', ev, { phase: 'main' });
    s.pending = { type: 'phase', seat: s.active, phase: 'main', prompt: 'Play cards and use Activate: Main abilities, then go to attack.' };
  },
  toAttack(s, step, ev) {
    if (!step.afterDelayed) {                              // "at the end of the main phase" abilities first
      s.cont.push({ k: 'toAttack', afterDelayed: true });
      runDelayed(s, 'endMain', ev);
      return;
    }
    if (!step.afterStart) {                                // "at the start of your attack phase" abilities
      s.phase = 'attack';
      log(s, 'Attack phase.', ev, { phase: 'attack' });
      s.cont.push({ k: 'toAttack', afterDelayed: true, afterStart: true });
      runDelayed(s, 'startAttack', ev);
      fire(s, 'attackPhase', { seat: s.active }, ev);
      return;
    }
    s.pending = { type: 'phase', seat: s.active, phase: 'attack', prompt: 'Attack with an active front line character, or end your turn.' };
  },
  attackChoice(s) {
    if (s.phase !== 'attack') return;
    s.pending = { type: 'phase', seat: s.active, phase: 'attack', prompt: 'Attack again, or end your turn.' };
  },
  mainChoice(s) {
    if (s.phase !== 'main') return;
    s.pending = { type: 'phase', seat: s.active, phase: 'main', prompt: 'Play cards and use Activate: Main abilities, then go to attack.' };
  },
  moveChoice(s) {
    if (s.phase !== 'move') return;
    s.pending = { type: 'phase', seat: s.active, phase: 'move', prompt: 'Move characters from your energy line to your front line, then go on.' };
  },
  toEnd(s, step, ev) {
    s.phase = 'end';
    log(s, 'End phase.', ev, { phase: 'end' });
    fire(s, 'endPhase', { seat: s.active }, ev);
    s.cont.push({ k: 'endRest' });
  },
  endRest(s, step, ev) {
    const p = P(s, s.active);
    for (const iid of [...p.front, ...p.energy]) C(s, iid).rest = false;      // AP cards stay resting (UA-8.5)
    if (p.hand.length > HAND_LIMIT) {
      s.pending = { type: 'choose', seat: s.active, op: 'handLimit', prompt: `Choose ${HAND_LIMIT} cards to keep; the rest go to your removal area.`,
        options: [...p.hand], min: HAND_LIMIT, max: HAND_LIMIT, zone: 'hand' };
      return;
    }
    s.cont.push({ k: 'endFinish' });
  },
  endFinish(s, step, ev) {
    if (!step.afterDelayed) {
      s.cont.push({ k: 'endFinish', afterDelayed: true });
      runDelayed(s, 'endTurn', ev);
      return;
    }
    expire(s, (m) => m.until === 'eot');
    for (const c of Object.values(s.cards)) { c.attacks = 0; c.blocks = 0; }
    s.battle = null;
    startTurn(s, other(s.active), ev);
  },
  // ----- battle -----
  afterAttackDecl(s, step, ev) {
    const b = s.battle;
    if (!b || !onField(C(s, b.att))) { s.battle = null; s.cont.push({ k: 'attackChoice' }); return; }
    if (b.target) { s.cont.push({ k: 'resolveBattle' }); return; }        // Snipe: no block (UA-10)
    const def = other(s.active);
    const att = C(s, b.att);
    const unblock = modsOf(s, att).filter((m) => m.unblockable).map((m) => m.unblockable);
    const blockers = P(s, def).front.filter((iid) => canBlock(s, C(s, iid)) && !unblock.some((f) => matches(s, C(s, iid), f, s.active)));
    if (!blockers.length) { s.cont.push({ k: 'notBlocked' }); return; }
    const must = modsOf(s, att).some((m) => m.mustBeBlocked);
    s.pending = { type: 'block', seat: def, attacker: b.att, options: blockers, must, prompt: `${cardName(s, C(s, b.att))} attacks you. ${must ? 'You must block it if able.' : 'Block with an active front line character?'}` };
  },
  notBlocked(s, step, ev) {
    fire(s, 'notBlocked', { iid: s.battle.att, seat: s.active }, ev);
    s.cont.push({ k: 'resolveBattle' });
  },
  resolveBattle(s, step, ev) {
    const b = s.battle;
    const att = C(s, b.att);
    if (!onField(att)) { s.battle = null; s.cont.push({ k: 'attackChoice' }); return; }
    const defIid = b.blocker || b.target;
    if (!defIid) {
      // attacking the player: 1 damage, or Damage N (+ Damage +N) (UA-8.4, UA-10)
      const kw = kwOf(s, att);
      const n = (kw.damage || 1) + (kw.damagePlus || 0);
      s.cont.push({ k: 'battleEnd' });
      fire(s, 'directDamage', { iid: att.iid, seat: s.active, n }, ev);
      dealDamage(s, other(s.active), n, ev, { by: att.iid });
      return;
    }
    const dc = C(s, defIid);
    if (!onField(dc)) { s.cont.push({ k: 'battleEnd' }); return; }
    const abp = bpOf(s, att), dbp = bpOf(s, dc);
    log(s, `Battle: ${cardName(s, att)} (${abp} BP) vs ${cardName(s, dc)} (${dbp} BP).`, ev, { battle: [att.iid, dc.iid] });
    s.cont.push({ k: 'battleEnd' });
    if (abp >= dbp) {
      b.won = true;
      sideline(s, dc.iid, ev, 'lost the battle');
      const kw = kwOf(s, att);
      const nullified = (b.nullify || hasKw(s, dc, 'nullifyImpact'));
      fire(s, 'winBattle', { iid: att.iid, seat: s.active, loser: dc.iid }, ev);
      if (kw.impact && !nullified) {
        const n = 1 + (kw.impactPlus || 0);
        s.cont.push({ k: 'impact', n, by: att.iid });
      }
    } else {
      b.won = false;
      log(s, `${cardName(s, att)} loses the battle (it stays on the field).`, ev);
      fire(s, 'loseBattle', { iid: att.iid, seat: s.active, winner: dc.iid }, ev);
      fire(s, 'winBattle', { iid: dc.iid, seat: dc.owner, loser: att.iid, defending: true }, ev);
    }
  },
  impact(s, step, ev) {
    log(s, `Impact: ${step.n} damage.`, ev);
    dealDamage(s, other(s.active), step.n, ev, { by: step.by, impact: true });
  },
  battleEnd(s, step, ev) {
    const b = s.battle;
    if (b) fire(s, 'battleEnd', { iid: b.att, seat: s.active }, ev);
    expire(s, (m) => m.until === 'battle');
    s.battle = null;
    s.cont.push({ k: 'attackChoice' });
  },
  // ----- damage: check each life card for its trigger, one at a time (UA-8.4) -----
  lifeCheck(s, step, ev) {
    const p = P(s, step.seat);
    if (!p.check.length) {
      if (!p.life.length) win(s, other(step.seat), `${nameOf(s, step.seat)} has no life left`, ev);
      return;
    }
    // one card at a time; with several the damaged player picks the order (UA-8.4)
    if (p.check.length > 1 && !step.ordered) {
      s.cont.push({ ...step, ordered: true });
      const withTrig = p.check.filter((iid) => D(s, C(s, iid)).trigger);
      if (withTrig.length > 1) {
        s.pending = { type: 'choose', seat: step.seat, op: 'lifeOrder', prompt: 'Choose which revealed life card to check first.', options: [...p.check], min: 1, max: 1, public: true };
        return;
      }
      return;
    }
    const iid = step.first && p.check.includes(step.first) ? step.first : p.check[0];
    const c = C(s, iid);
    const d = D(s, c);
    s.cont.push({ k: 'lifeCheck', seat: step.seat });
    if (d.trigger) {
      s.pending = { type: 'trigger', seat: step.seat, card: iid, trigger: d.trigger, prompt: `Life card ${d.name}: activate its ${d.trigger.label} trigger? (${d.trigger.text})` };
    } else {
      moveCard(s, iid, 'side', ev);
    }
  },
};

// deal damage to a player: the dealer picks that many life cards (we take them from the top: life is face down, so
// the pick carries no information) and they're revealed and checked (UA-8.4)
export function dealDamage(s, seat, n, ev, info = {}) {
  const p = P(s, seat);
  const take = Math.min(n, p.life.length);
  log(s, `${nameOf(s, seat)} takes ${n} damage.`, ev, { damage: seat, n });
  const revealed = [];
  for (let i = 0; i < take; i++) {
    const iid = p.life.shift();
    const c = C(s, iid);
    c.zone = 'check';
    p.check.push(iid);
    revealed.push(iid);
  }
  if (revealed.length) log(s, `Revealed from life: ${revealed.map((i) => cardName(s, C(s, i))).join(', ')}.`, ev, { reveal: revealed });
  s.cont.push({ k: 'lifeCheck', seat });
}

export function canAttack(s, c) {
  return onField(c) && c.zone === 'front' && !c.rest && D(s, c).type === 'character' && !flagOf(s, c, 'cantAttack');
}
export function canBlock(s, c) {
  return onField(c) && c.zone === 'front' && !c.rest && D(s, c).type === 'character' && !flagOf(s, c, 'cantBlock');
}

// ---------- actions ----------
function needPending(s, seat, type, phase) {
  const p = s.pending;
  if (s.winner != null) throw RE('The game is over.');
  if (!p || p.seat !== seat || p.type !== type || (phase && p.phase !== phase)) throw RE(phase ? `You can only do that in your ${phase} phase.` : 'You can’t do that now.');
  return p;
}
function inHand(s, seat, iid) {
  const c = C(s, iid);
  if (!c || c.owner !== seat || c.zone !== 'hand') throw RE('That card isn’t in your hand.');
  return c;
}
function ownField(s, seat, iid) {
  const c = C(s, iid);
  if (!c || c.owner !== seat || !onField(c)) throw RE('That card isn’t on your field.');
  return c;
}

// raid targets for this card: characters on your field matching the spec that don't have Raid themselves (UA-8.3)
export function raidTargets(s, seat, c) {
  const r = D(s, c).raid;
  if (!r) return [];
  return [...P(s, seat).front, ...P(s, seat).energy].filter((iid) => {
    const t = C(s, iid), td = D(s, t);
    if (td.type !== 'character' || td.raid) return false;
    if (r.kind === 'name') return nameKeyEq(td.name, r.value);
    return (td.affinities || []).some((a) => nameKeyEq(a, r.value));
  });
}
const nameKeyEq = (a, b) => String(a).toLowerCase().replace(/\s+/g, ' ').trim() === String(b).toLowerCase().replace(/\s+/g, ' ').trim();

function playCard(s, seat, a, ev, { free = false, fromTrigger = false } = {}) {
  const c = fromTrigger ? C(s, a.iid) : inHand(s, seat, a.iid);
  const d = D(s, c);
  if (!free) {
    if (!energyOk(s, seat, d, c)) throw RE(`${d.name} needs ${energyNeed(s, seat, c)} ${d.color} energy; your energy line makes ${energyOf(s, seat)[d.color] || 0}.`);
  }
  const cost = free ? 0 : apCost(s, seat, c);
  if (!free) {
    // "reduce the AP cost of the next … card you use this turn": used up by this card
    const p0 = P(s, seat);
    const used = (p0.costMods || []).filter((m) => m.next && matches(s, c, m.filter, seat));
    if (used.length) p0.costMods = p0.costMods.filter((m) => !used.includes(m));
  }
  if (!a.raid && s.compiled[c.no]?.raidOnly && !fromTrigger) throw RE(`${d.name} can only be played by performing Raid with it.`);
  if (!a.raid && a.line === 'front' && s.compiled[c.no]?.noFront) throw RE(`${d.name} can't be played onto your front line.`);
  if (!a.raid && a.line === 'energy' && s.compiled[c.no]?.noEnergy) throw RE(`${d.name} can't be played onto your energy line.`);
  if (a.raid) {
    const targets = raidTargets(s, seat, c);
    if (!targets.includes(a.onto)) throw RE(`${d.name} can't Raid onto that card.`);
    if (!free) payAp(s, seat, cost);
    const t = C(s, a.onto);
    const line = t.zone;
    const p = P(s, seat);
    const idx = p[line].indexOf(t.iid);
    // the raider takes the lower card's place; the lower card (and anything under it) goes underneath (UA-8.3)
    detach(s, c);
    p[line][idx] = c.iid;
    c.zone = line;
    freshOnField(s, c);
    c.under = [t.iid, ...t.under];
    for (const u of c.under) { const uc = C(s, u); uc.zone = 'under'; uc.parent = c.iid; uc.mods = []; uc.under = []; }
    t.under = [];
    c.rest = false;                                         // switch to active
    if (line === 'energy' && a.toFront !== false && p.front.length < LINE_MAX) { p.energy.splice(p.energy.indexOf(c.iid), 1); p.front.push(c.iid); c.zone = 'front'; }
    else if (line === 'energy' && a.toFront && a.remove) { makeRoom(s, seat, 'front', a.remove, ev); p.energy.splice(p.energy.indexOf(c.iid), 1); p.front.push(c.iid); c.zone = 'front'; }
    c.raided = true;
    log(s, `${nameOf(s, seat)} Raids ${d.name} onto ${cardName(s, t)}${c.zone === 'front' ? ' and moves it to the front line' : ''}.`, ev, { play: c.iid });
    fire(s, 'played', { iid: c.iid, seat, raid: true }, ev);
    return c;
  }
  if (d.type === 'event') {
    if (!free) payAp(s, seat, cost);
    detach(s, c);
    c.zone = 'check';
    P(s, seat).check.push(c.iid);
    log(s, `${nameOf(s, seat)} uses ${d.name}.`, ev, { play: c.iid });
    (s.usedEvent ||= {})[seat] = s.turnNo;
    const ab = s.compiled[c.no]?.event;
    s.cont.push({ k: 'eventDone', iid: c.iid });
    if (ab) s.queue.push(newJob(s, c, ab, 'event', {}));
    return c;
  }
  const line = d.type === 'site' ? 'energy' : a.line;
  if (line !== 'front' && line !== 'energy') throw RE('Choose the front line or the energy line.');
  if (d.type === 'site' && a.line === 'front') throw RE('Sites can only go on the energy line.');
  makeRoom(s, seat, line, a.remove, ev);
  if (!free) payAp(s, seat, cost);
  c.raided = false;
  moveCard(s, c.iid, line, ev, { active: !!s.compiled[c.no]?.entersActive });
  log(s, `${nameOf(s, seat)} plays ${d.name} onto the ${line === 'front' ? 'front line' : 'energy line'}.`, ev, { play: c.iid });
  fire(s, 'played', { iid: c.iid, seat }, ev);
  return c;
}
STEPS.eventDone = (s, step, ev) => {
  const c = C(s, step.iid);
  if (c.zone === 'check') moveCard(s, c.iid, 'side', ev);
};

const ACTIONS = {
  mulligan(s, seat, a, ev) {
    needPending(s, seat, 'mulligan');
    const p = P(s, seat);
    p.mulligan = !!a.redraw;
    if (a.redraw) {
      for (const iid of p.hand) { C(s, iid).zone = 'deck'; p.deck.push(iid); }
      p.hand = [];
      drawCards(s, seat, OPENING, null);
      shuffle(s, p.deck);
      log(s, `${nameOf(s, seat)} mulligans.`, ev);
    } else log(s, `${nameOf(s, seat)} keeps their hand.`, ev);
    const next = other(seat);
    s.pending = P(s, next).mulligan == null ? { type: 'mulligan', seat: next, prompt: 'Keep this hand, or shuffle it away and draw 7 new cards (once)?' } : null;
    if (!s.pending) finishSetup(s, ev);
  },
  extraDraw(s, seat, a, ev) {
    needPending(s, seat, 'phase', 'start');
    const p = P(s, seat);
    if (p.extraDrawn) throw RE('You already took an extra draw this turn.');
    payAp(s, seat, 1);
    p.extraDrawn = true;
    log(s, `${nameOf(s, seat)} pays 1 AP for an extra draw.`, ev);
    drawCards(s, seat, 1, ev);
    s.pending = null;
    s.cont.push({ k: 'startChoice' });
  },
  next(s, seat, a, ev) {
    const pend = s.pending;
    if (!pend || pend.seat !== seat || pend.type !== 'phase') throw RE('You can’t move on yet.');
    s.pending = null;
    const go = { start: 'toMove', move: 'toMain', main: 'toAttack', attack: 'toEnd' }[pend.phase];
    s.cont.push({ k: go });
  },
  move(s, seat, a, ev) {
    needPending(s, seat, 'phase', 'move');
    const c = ownField(s, seat, a.iid);
    const d = D(s, c);
    if (d.type !== 'character') throw RE('Sites can’t move.');
    const p = P(s, seat);
    if (c.zone === 'energy') {
      if (s.compiled[c.no]?.noFront) throw RE(`${d.name} can't move to your front line.`);
      if (p.front.length >= LINE_MAX) makeRoom(s, seat, 'front', a.remove, ev);
      p.energy.splice(p.energy.indexOf(c.iid), 1); p.front.push(c.iid); c.zone = 'front';
      log(s, `${nameOf(s, seat)} moves ${d.name} to the front line.`, ev, { moved: c.iid });
    } else {
      if (!hasKw(s, c, 'step')) throw RE(`${d.name} doesn’t have Step, so it can’t move to the energy line.`);
      if (p.energy.length >= LINE_MAX) {
        if (a.swap) {
          const o = ownField(s, seat, a.swap);
          if (o.zone !== 'energy') throw RE('Swap with a character on your energy line.');
          const fi = p.front.indexOf(c.iid), ei = p.energy.indexOf(o.iid);
          p.front[fi] = o.iid; p.energy[ei] = c.iid; o.zone = 'front'; c.zone = 'energy';
          log(s, `${nameOf(s, seat)} swaps ${d.name} with ${cardName(s, o)} (Step).`, ev, { moved: c.iid });
          return;
        }
        makeRoom(s, seat, 'energy', a.remove, ev);
      }
      p.front.splice(p.front.indexOf(c.iid), 1); p.energy.push(c.iid); c.zone = 'energy';
      log(s, `${nameOf(s, seat)} moves ${d.name} to the energy line (Step).`, ev, { moved: c.iid });
    }
  },
  play(s, seat, a, ev) {
    needPending(s, seat, 'phase', 'main');
    s.pending = null;
    s.cont.push({ k: 'mainChoice' });          // under whatever the card itself leaves to finish (an event's sideline step)
    playCard(s, seat, a, ev);
  },
  activate(s, seat, a, ev) {
    needPending(s, seat, 'phase', 'main');
    const c = ownField(s, seat, a.iid);
    const ab = s.compiled[c.no]?.abilities?.[a.ab];
    if (!ab || ab.timing !== 'activate') throw RE('That card has no such Activate: Main ability.');
    if (ab.once && c.once?.[a.ab] === s.turnNo) throw RE('Once Per Turn: already used this turn.');
    if (ab.cond && !evalCond(s, ab.cond, { src: c.iid, seat })) throw RE('Its condition isn’t met.');
    payCosts(s, seat, c, ab.cost || [], a, ev);
    if (ab.once) (c.once ||= {})[a.ab] = s.turnNo;
    log(s, `${nameOf(s, seat)} activates ${D(s, c).name}.`, ev, { activate: c.iid });
    s.pending = null;
    s.queue.push(newJob(s, c, ab, a.ab, {}));
    s.cont.push({ k: 'mainChoice' });
  },
  attack(s, seat, a, ev) {
    needPending(s, seat, 'phase', 'attack');
    const c = ownField(s, seat, a.iid);
    if (!canAttack(s, c)) throw RE('Only an active character on your front line can attack.');
    let target = null;
    if (a.target) {
      if (!hasKw(s, c, 'snipe')) throw RE('Only a character with Snipe can attack a character.');
      const t = C(s, a.target);
      if (!t || t.owner === seat || t.zone !== 'front') throw RE('Snipe targets a character on your opponent’s front line.');
      target = t.iid;
    }
    s.pending = null;
    c.rest = true;
    c.attacks = (c.attacks || 0) + 1;
    s.battle = { att: c.iid, target, blocker: null, won: null };
    log(s, `${nameOf(s, seat)} attacks with ${D(s, c).name}${target ? ` (Snipe → ${cardName(s, C(s, target))})` : ''}.`, ev, { attack: c.iid, target });
    if (c.attacks === 1 && hasKw(s, c, 'doubleAttack')) { c.rest = false; log(s, `${D(s, c).name} switches to active (Double Attack).`, ev); }
    s.cont.push({ k: 'afterAttackDecl' });
    fire(s, 'attack', { iid: c.iid, seat, target }, ev);
  },
  block(s, seat, a, ev) {
    const pend = needPending(s, seat, 'block');
    s.pending = null;
    if (!a.iid) {
      if (pend.must) throw RE('You must block this attack if able.');
      log(s, `${nameOf(s, seat)} doesn’t block.`, ev); s.cont.push({ k: 'notBlocked' }); return;
    }
    if (!pend.options.includes(a.iid)) throw RE('Block with an active character on your front line.');
    const c = C(s, a.iid);
    c.rest = true;
    c.blocks = (c.blocks || 0) + 1;
    s.battle.blocker = c.iid;
    log(s, `${nameOf(s, seat)} blocks with ${D(s, c).name}.`, ev, { block: c.iid });
    if (c.blocks === 1 && hasKw(s, c, 'doubleBlock')) { c.rest = false; log(s, `${D(s, c).name} switches to active (Double Block).`, ev); }
    s.cont.push({ k: 'resolveBattle' });
    fire(s, 'block', { iid: c.iid, seat, attacker: s.battle.att }, ev);
  },
  trigger(s, seat, a, ev) {
    const pend = needPending(s, seat, 'trigger');
    s.pending = null;
    const c = C(s, pend.card);
    const d = D(s, c);
    if (!a.use) { log(s, `${nameOf(s, seat)} doesn’t use ${d.name}'s trigger.`, ev); moveCard(s, c.iid, 'side', ev); return; }
    log(s, `${nameOf(s, seat)} activates ${d.name}'s ${d.trigger.label} trigger.`, ev, { trigger: c.iid });
    const t = d.trigger.type;
    if (t === 'get') { moveCard(s, c.iid, 'hand', ev); log(s, `${d.name} goes to ${nameOf(s, seat)}'s hand.`, ev); return; }
    if (t === 'raid') {
      // add to hand, or Raid with it if you have the required energy (AP isn't paid for a trigger)
      if (a.raidOnto) {
        if (!energyOk(s, seat, d)) throw RE(`You don't have the required energy to Raid with ${d.name}.`);
        playCard(s, seat, { iid: c.iid, raid: true, onto: a.raidOnto, toFront: a.toFront }, ev, { free: true, fromTrigger: true });
      } else { moveCard(s, c.iid, 'hand', ev); log(s, `${d.name} goes to ${nameOf(s, seat)}'s hand.`, ev); }
      return;
    }
    const ab = s.compiled[c.no]?.trigger;
    s.cont.push({ k: 'triggerDone', iid: c.iid });
    if (ab) s.queue.push(newJob(s, c, ab, 'trigger', {}));
  },
  choose(s, seat, a, ev) {
    const pend = needPending(s, seat, 'choose');
    const picks = Array.isArray(a.picks) ? [...new Set(a.picks.map(String))] : [];
    if (picks.length < (pend.min ?? 0) || picks.length > (pend.max ?? picks.length)) throw RE(`Choose ${pend.min === pend.max ? pend.min : `${pend.min}–${pend.max}`}.`);
    if (pend.options && picks.some((p) => !pend.options.includes(p))) throw RE('That isn’t one of the choices.');
    s.pending = null;
    if (pend.op === 'handLimit') {
      const p = P(s, seat);
      const drop = p.hand.filter((iid) => !picks.includes(iid));
      for (const iid of drop) moveCard(s, iid, 'removal', ev);
      log(s, `${nameOf(s, seat)} keeps ${HAND_LIMIT} cards and removes ${drop.length}.`, ev);
      s.cont.push({ k: 'endFinish' });
      return;
    }
    if (pend.op === 'lifeOrder') {
      const top = s.cont[s.cont.length - 1];
      if (top?.k === 'lifeCheck') top.first = picks[0];
      return;
    }
    // an ability's choice: hand it back to the job that asked
    const job = s.queue.find((j) => j.id === pend.job);
    if (job) { job.ctx.answer = picks; job.ctx.answered = true; }
  },
  yesno(s, seat, a, ev) {
    const pend = needPending(s, seat, 'yesno');
    s.pending = null;
    const job = s.queue.find((j) => j.id === pend.job);
    if (job) { job.ctx.answer = !!a.yes; job.ctx.answered = true; }
  },
  // ----- resolving by hand (a line the compiler couldn't read) -----
  manualDone(s, seat, a, ev) {
    const pend = needPending(s, seat, 'manual');
    s.pending = null;
    const i = s.queue.findIndex((j) => j.id === pend.job);
    if (i >= 0) s.queue.splice(i, 1);
    log(s, `${nameOf(s, seat)} finishes resolving ${cardName(s, C(s, pend.card))}.`, ev);
  },
  manual(s, seat, a, ev) {
    const pend = s.pending;
    if (!pend || pend.seat !== seat || pend.type !== 'manual') throw RE('Table actions are for resolving an ability by hand.');
    const c = a.iid ? C(s, a.iid) : null;
    switch (a.op) {
      case 'draw': drawCards(s, seat, Math.max(1, Math.min(5, Number(a.n) || 1)), ev); break;
      case 'rest': if (!onField(c)) throw RE('Pick a card on the field.'); c.rest = !!a.rest; log(s, `${cardName(s, c)} is now ${c.rest ? 'resting' : 'active'}.`, ev); break;
      case 'bp': if (!onField(c)) throw RE('Pick a card on the field.'); c.mods.push({ bp: Math.trunc(Number(a.n) || 0), until: a.until === 'sont' ? 'sont' : 'eot', who: seat }); log(s, `${cardName(s, c)} ${Number(a.n) >= 0 ? 'gains' : 'loses'} ${Math.abs(Number(a.n) || 0)} BP.`, ev); break;
      case 'sideline': if (!onField(c)) throw RE('Pick a card on the field.'); sideline(s, c.iid, ev, 'by an ability'); break;
      case 'move': {
        if (!c) throw RE('Pick a card.');
        const to = ['hand', 'side', 'removal', 'deckTop', 'deckBottom', 'life', 'front', 'energy'].includes(a.to) ? a.to : null;
        if (!to) throw RE('Pick where it goes.');
        if ((to === 'front' || to === 'energy') && P(s, c.owner)[to].length >= LINE_MAX) throw RE('That line is full.');
        moveCard(s, c.iid, to, ev);
        log(s, `${cardName(s, c)} → ${to}.`, ev);
        break;
      }
      case 'ap': { const p = P(s, seat); const want = !!a.active; const i = p.ap.findIndex((x) => x !== want); if (i >= 0) p.ap[i] = want; log(s, `${nameOf(s, seat)} switches an AP card to ${want ? 'active' : 'resting'}.`, ev); break; }
      case 'shuffle': shuffle(s, P(s, seat).deck); log(s, `${nameOf(s, seat)} shuffles their deck.`, ev); break;
      default: throw RE('Unknown table action.');
    }
  },
  concede(s, seat, a, ev) {
    if (s.winner != null) throw RE('The game is over.');
    log(s, `${nameOf(s, seat)} concedes.`, ev);
    win(s, other(seat), 'concession', ev);
  },
};
STEPS.triggerDone = (s, step, ev) => {
  const c = C(s, step.iid);
  if (c.zone === 'check') moveCard(s, c.iid, 'side', ev);
};

function payCosts(s, seat, c, cost, a, ev) {
  for (const k of cost) {
    if (k.k === 'rest') { if (c.rest) throw RE('It has to be active to switch it to resting.'); }
    else if (k.k === 'ap') { if (apActive(s, seat) < k.n) throw RE(`That costs ${k.n} AP.`); }
    else if (k.k === 'discard') {
      const picks = Array.isArray(a.discard) ? a.discard : [];
      if (picks.length !== k.n || picks.some((iid) => C(s, iid)?.owner !== seat || C(s, iid)?.zone !== 'hand')) throw RE(`Choose ${k.n} card${k.n > 1 ? 's' : ''} from your hand to place into your sideline.`);
    } else if (k.k === 'removeSide') {
      if (P(s, seat).side.length < k.n) throw RE(`That needs ${k.n} cards in your sideline.`);
    }
  }
  for (const k of cost) {
    if (k.k === 'rest') c.rest = true;
    else if (k.k === 'ap') payAp(s, seat, k.n);
    else if (k.k === 'discard') for (const iid of a.discard) moveCard(s, iid, 'side', ev);
    else if (k.k === 'sidelineSelf') sideline(s, c.iid, ev, 'cost');
    else if (k.k === 'removeSide') { const side = P(s, seat).side; for (let i = 0; i < k.n; i++) moveCard(s, side[side.length - 1], 'removal', ev); }
  }
}

export function applyAction(s, seat, a) {
  const fn = ACTIONS[a?.type];
  if (!fn) throw RE(`Unknown action ${a?.type}.`);
  const { defs, compiled, ...rest } = s;               // defs and compiled abilities never change during a game
  const snap = JSON.stringify(rest);
  const ev = [];
  try {
    fn(s, seat, a, ev);
    pump(s, ev);
  } catch (e) {
    const back = JSON.parse(snap);
    for (const k of Object.keys(s)) delete s[k];
    Object.assign(s, back, { defs, compiled });
    throw e;
  }
  return ev;
}

// ---------- what a seat can do ----------
export function legalActions(s, seat) {
  const out = [];
  const pend = s.pending;
  if (s.winner != null || !pend || pend.seat !== seat) return out;
  const p = P(s, seat);
  switch (pend.type) {
    case 'mulligan': out.push({ type: 'mulligan', redraw: false }, { type: 'mulligan', redraw: true }); break;
    case 'trigger': {
      out.push({ type: 'trigger', use: false });
      const d = D(s, C(s, pend.card));
      if (d.trigger.type === 'raid') {
        out.push({ type: 'trigger', use: true });
        if (energyOk(s, seat, d)) for (const t of raidTargets(s, seat, C(s, pend.card))) out.push({ type: 'trigger', use: true, raidOnto: t, toFront: true });
      } else out.push({ type: 'trigger', use: true });
      break;
    }
    case 'block': if (!pend.must) out.push({ type: 'block', iid: null }); out.push(...pend.options.map((iid) => ({ type: 'block', iid }))); break;
    case 'yesno': out.push({ type: 'yesno', yes: true }, { type: 'yesno', yes: false }); break;
    case 'choose': {
      // enumerate small choices; big ones get a few sensible picks
      const opts = pend.options || [];
      const combos = [];
      const k = Math.min(pend.max, opts.length);
      const kmin = Math.min(pend.min, opts.length);
      const pick = (start, acc) => {
        if (combos.length > 40) return;
        if (acc.length >= kmin && acc.length <= k) combos.push([...acc]);
        if (acc.length === k) return;
        for (let i = start; i < opts.length; i++) { acc.push(opts[i]); pick(i + 1, acc); acc.pop(); }
      };
      pick(0, []);
      for (const c of combos) out.push({ type: 'choose', picks: c });
      break;
    }
    case 'manual': out.push({ type: 'manualDone' }); break;
    case 'phase': {
      if (pend.phase === 'start') {
        if (!p.extraDrawn && apActive(s, seat) >= 1 && p.deck.length) out.push({ type: 'extraDraw' });
      } else if (pend.phase === 'move') {
        for (const iid of p.energy) {
          const c = C(s, iid);
          if (D(s, c).type !== 'character' || s.compiled[c.no]?.noFront) continue;
          if (p.front.length < LINE_MAX) out.push({ type: 'move', iid });
        }
        for (const iid of p.front) if (hasKw(s, C(s, iid), 'step') && p.energy.length < LINE_MAX) out.push({ type: 'move', iid });
      } else if (pend.phase === 'main') {
        for (const iid of p.hand) {
          const c = C(s, iid), d = D(s, c);
          if (!energyOk(s, seat, d, c) || apActive(s, seat) < apCost(s, seat, c)) continue;
          if (d.type === 'event') out.push({ type: 'play', iid });
          else if (d.type === 'site') { if (p.energy.length < LINE_MAX) out.push({ type: 'play', iid, line: 'energy' }); }
          else if (d.type === 'character') {
            const cc = s.compiled[c.no] || {};
            if (!cc.raidOnly && !cc.noFront && p.front.length < LINE_MAX) out.push({ type: 'play', iid, line: 'front' });
            if (!cc.raidOnly && !cc.noEnergy && p.energy.length < LINE_MAX) out.push({ type: 'play', iid, line: 'energy' });
            for (const t of raidTargets(s, seat, c)) out.push({ type: 'play', iid, raid: true, onto: t, toFront: true });
          }
        }
        for (const iid of [...p.front, ...p.energy]) {
          const c = C(s, iid);
          (s.compiled[c.no]?.abilities || []).forEach((ab, i) => {
            if (ab.timing !== 'activate') return;
            if (ab.once && c.once?.[i] === s.turnNo) return;
            if (ab.cond && !evalCond(s, ab.cond, { src: iid, seat })) return;
            const cost = ab.cost || [];
            if (cost.some((k) => k.k === 'rest') && c.rest) return;
            const apNeed = cost.filter((k) => k.k === 'ap').reduce((n, k) => n + k.n, 0);
            if (apActive(s, seat) < apNeed) return;
            const disc = cost.find((k) => k.k === 'discard');
            if (disc && p.hand.length < disc.n) return;
            const rs = cost.find((k) => k.k === 'removeSide');
            if (rs && p.side.length < rs.n) return;
            out.push({ type: 'activate', iid, ab: i, label: ab.text, ...(disc ? { discard: p.hand.slice(0, disc.n), needDiscard: disc.n } : {}) });
          });
        }
      } else if (pend.phase === 'attack') {
        for (const iid of p.front) {
          const c = C(s, iid);
          if (!canAttack(s, c)) continue;
          out.push({ type: 'attack', iid });
          if (hasKw(s, c, 'snipe')) for (const t of P(s, other(seat)).front) out.push({ type: 'attack', iid, target: t });
        }
      }
      out.push({ type: 'next' });
      break;
    }
    default: break;
  }
  return out;
}

// ---------- views ----------
function pubCard(s, c, seat) {
  const out = { iid: c.iid, no: c.no, owner: c.owner, zone: c.zone, rest: !!c.rest };
  if (onField(c)) {
    out.bp = bpOf(s, c);
    out.kw = kwOf(s, c);
    if (c.under.length) out.under = c.under.map((u) => ({ iid: u, no: C(s, u).no }));
    const mods = modsOf(s, c).filter((m) => m.bp || m.kw || m.cantAttack || m.cantBlock || m.gen);
    if (mods.length) out.mods = mods.map((m) => ({ bp: m.bp || 0, kw: m.kw, cantAttack: m.cantAttack, cantBlock: m.cantBlock, gen: m.gen, until: m.until, static: !!m.static }));
  }
  return out;
}
export function viewFor(s, seat) {
  const v = {
    you: seat, active: s.active, first: s.first, turnNo: s.turnNo, phase: s.phase, winner: s.winner,
    battle: s.battle, log: s.log.slice(-80),
    pending: s.pending ? { ...s.pending, options: s.pending.seat === seat || s.pending.public ? s.pending.options : undefined } : null,
    players: s.players.map((p, i) => {
      const mine = i === seat;
      const pub = (list) => list.map((iid) => pubCard(s, C(s, iid), seat));
      return {
        name: p.name, turns: p.turns,
        hand: mine ? pub(p.hand) : p.hand.length,
        deck: p.deck.length, life: p.life.length,
        side: pub(p.side), removal: pub(p.removal), check: pub(p.check),
        front: pub(p.front), energy: pub(p.energy),
        ap: p.ap.map((x) => !!x), extraDrawn: p.extraDrawn,
        energyGen: energyOf(s, i),
      };
    }),
  };
  if (v.pending?.seat === seat) {
    v.legal = legalActions(s, seat);
    // the cards behind a choice's options (own hand, looked-at deck cards, public zones) so the chooser can see them
    if (Array.isArray(s.pending.options)) {
      const oc = {};
      for (const o of s.pending.options) if (s.cards[o]) oc[o] = s.cards[o].no;
      for (const o of s.pending.looked || []) if (s.cards[o]) oc[o] = s.cards[o].no;
      v.pending.optCards = oc;
    }
    if (s.pending.type === 'manual' && s.queue[0]) v.pending.manualText = s.queue[0].text;
  }
  return v;
}
