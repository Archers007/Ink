export function checkInvariants(s) {
  const seen = new Set();
  for (const [seat, p] of s.players.entries()) {
    for (const z of ['deck', 'hand', 'life', 'side', 'removal', 'front', 'energy', 'check']) {
      for (const iid of p[z]) {
        if (seen.has(iid)) throw new Error(`card ${iid} in two places`);
        seen.add(iid);
        const c = s.cards[iid];
        if (c.zone !== z) throw new Error(`card ${iid} zone ${c.zone} but listed in ${z}`);
        if (c.owner !== seat) throw new Error(`card ${iid} in the wrong player's ${z}`);
        for (const u of c.under) { if (seen.has(u)) throw new Error(`under ${u} twice`); seen.add(u); if (s.cards[u].zone !== 'under') throw new Error(`under ${u} zone ${s.cards[u].zone}`); }
      }
    }
    if (p.front.length > LINE_MAX || p.energy.length > LINE_MAX) throw new Error('line over 4');
  }
  if (seen.size !== Object.keys(s.cards).length) throw new Error(`lost cards: ${Object.keys(s.cards).length - seen.size}`);
}
