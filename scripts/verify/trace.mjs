// Comprehensive Rules traceability: which rulebook sections the code builds on, and which the tests exercise.
// Citations are "CR 4.6.7" in comments / strings and `cr: '4.6.7'` fields (rulebook/*.js, features.js). Writes the
// matrix to scripts/verify/cr-trace.md and fails on a citation of a section that doesn't exist.
//   node scripts/verify/trace.mjs [--holes]
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { sections, quote, CR_VERSION } from '../../game/rulebook/cr.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = path.join(d, f); if (f === 'node_modules' || f.startsWith('.')) continue; if (statSync(p).isDirectory()) walk(p); else if (/\.m?js$/.test(f)) files.push(p); } };
for (const d of ['game', 'public/js', 'scripts', 'tools']) walk(path.join(ROOT, d));

const ALL = sections();
const KNOWN = new Set(ALL);
const cites = new Map();                                              // id → { code: Set, test: Set }
const dangling = [];
const RX = /\bCR\s+(\d+(?:\.\d+)+)|\bcr:\s*'(\d+(?:\.\d+)*)'|\[CR (\d+(?:\.\d+)+)\]/g;
for (const f of files) {
  const rel = path.relative(ROOT, f);
  const isTest = /^scripts\/(?:test-|sim-|oracles\/|verify\/)/.test(rel);
  readFileSync(f, 'utf8').split('\n').forEach((line, i) => {
    // a bare section number in a comment ("— 4.6.4.2", "(8.11)") counts when it names a real section
    const comment = line.includes('//') ? line.slice(line.indexOf('//')) : '';
    for (const m of comment.matchAll(/(?<![\d.])(\d{1,2}\.\d{1,2}(?:\.\d{1,2}){0,3})(?![\d.]*\d)/g)) {
      if (!KNOWN.has(m[1]) || /\bCR\s+$/.test(comment.slice(0, m.index))) continue;
      const e = cites.get(m[1]) || cites.set(m[1], { code: new Set(), test: new Set() }).get(m[1]);
      (isTest ? e.test : e.code).add(rel);
    }
    for (const m of line.matchAll(RX)) {
      const id = (m[1] || m[2] || m[3]).replace(/\.$/, '');
      if (!KNOWN.has(id)) { if (rel !== 'scripts/verify/trace.mjs') dangling.push(`${rel}:${i + 1} cites CR ${id}`); continue; }
      const e = cites.get(id) || cites.set(id, { code: new Set(), test: new Set() }).get(id);
      (isTest ? e.test : e.code).add(rel);
    }
  });
}
// a section counts as covered if it or a section inside it is cited
const below = (id) => [...cites.keys()].filter((k) => k === id || k.startsWith(`${id}.`));
const status = (id) => {
  const c = cites.get(id);
  if (c?.code.size && c.test.size) return 'code + tests';
  if (c?.code.size) return 'code';
  if (c?.test.size) return 'tests';
  if (below(id).length) return 'inside cited';
  const parts = id.split('.');
  for (let k = parts.length - 1; k >= 1; k--) if (cites.has(parts.slice(0, k).join('.'))) return 'under a cited section';
  return '—';
};
const rows = ALL.filter((id) => +id.split('.')[0] >= 1 && +id.split('.')[0] <= 10);
const count = {}; for (const id of rows) count[status(id)] = (count[status(id)] || 0) + 1;
const md = [
  `# Comprehensive Rules traceability (CR ${CR_VERSION})`, '',
  'Generated by `node scripts/verify/trace.mjs` — which sections the code cites, and which the tests cite.', '',
  `| status | sections |`, '|---|---|', ...Object.entries(count).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`), '',
  '| CR | rule | status | code | tests |', '|---|---|---|---|---|',
  ...rows.map((id) => { const c = cites.get(id); return `| ${id} | ${(quote(id, 70) || '').replace(/\|/g, '/')} | ${status(id)} | ${c ? [...c.code].join(', ') : ''} | ${c ? [...c.test].join(', ') : ''} |`; }),
  '',
].join('\n');
writeFileSync(path.join(ROOT, 'scripts/verify/cr-trace.md'), md);
const lvl2 = rows.filter((id) => id.split('.').length === 2);
const holes = lvl2.filter((id) => !below(id).length);
console.log(`trace: ${rows.length} CR sections · ${cites.size} cited (${[...cites.values()].filter((e) => e.test.size).length} by tests) · ${Object.entries(count).map(([k, v]) => `${k} ${v}`).join(' · ')} → scripts/verify/cr-trace.md`);
console.log(`trace: ${holes.length} of ${lvl2.length} top-level sections have nothing cited inside them${process.argv.includes('--holes') ? `:\n${holes.map((h) => `  ${h} ${quote(h, 70)}`).join('\n')}` : ''}`);
for (const d of dangling) console.log(`  ✗ ${d} — no such section`);
console.log(dangling.length ? 'trace: FAIL — citations of sections that don\'t exist' : 'trace: OK — every citation is a real section');
process.exitCode = dangling.length ? 1 : 0;
